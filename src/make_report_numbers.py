"""Generate report/numbers.md: every number the report needs, each table with its source file and columns.
Nothing is typed by hand: all values are read from results/ and data/processed/. Usage: python -m src.make_report_numbers
"""
import json

import numpy as np
import pandas as pd

from src import config as C
from src.make_readme_numbers import md_table

R = C.RESULTS


def csv(name):
    return pd.read_csv(R / name)


def section(out, title, source, df, fmt="{:.3f}", note=None):
    out += [f"## {title}", f"*Source:* `{source}`" + (f" - {note}" if note else ""), "", md_table(df, fmt), ""]


def main():
    out = ["# Numbers for the report", "", "Generated by `src/make_report_numbers.py` from the result files named under each table "
           "(columns are the CSV column names). Do not edit by hand; rerun the script.", ""]
    primary = json.loads((R / "headline_scorer.json").read_text())["primary"]

    gate = csv("validity_gate.csv")
    section(out, "1. Validity gate coverage", "results/validity_gate.csv",
            gate[["check", "regime", "K_frac", "K", "delta", "coverage", "expected_coverage_theory", "nominal", "se", "gating", "pass"]],
            note="coverage vs nominal; `gating` rows decide PASS (coverage >= nominal - 2 SE); non-gating rows are informational")

    fx, fr = csv("miss_rate_certified_vs_realised.csv"), csv("miss_rate_fraction_budget.csv")
    d = lambda df, sc=None: df[np.isclose(df.delta, 0.10) & ((df.scorer == sc) if sc else True)]
    m = d(fx, "direct")[["K_frac", "K", "certified_bound", "test_miss_rate_realised", "covered"]].merge(
        d(fr)[["K_frac", "K", "certified_bound", "test_miss_rate_realised", "covered"]], on="K_frac", suffixes=("_fixed", "_fraction"))
    section(out, "2a. Fixed-count vs fraction-of-volume budget (direct scorer, delta 0.10)",
            "results/miss_rate_certified_vs_realised.csv (scorer = direct) and results/miss_rate_fraction_budget.csv", m)
    section(out, "2b. Fixed-count budget, primary scorer (delta 0.10 and 0.05)", "results/miss_rate_certified_vs_realised.csv (scorer = " + primary + ")",
            fx[fx.scorer == primary][["K_frac", "K", "delta", "n_cal_pos", "cal_miss_rate", "certified_bound", "n_test_pos", "test_miss_rate_realised", "covered", "recall_at_K_test"]])

    h1 = csv("coverage_by_typology_primary.csv")
    section(out, "3a. H1 by typology, PRIMARY scorer (delta 0.10, K = 1% and 5% of period)", "results/coverage_by_typology_primary.csv",
            h1[np.isclose(h1.delta, 0.10) & h1.K_frac.isin([0.01, 0.05])][["typology", "K_frac", "n_cal_pos", "n_test_pos", "group_cal_miss", "group_bound", "pooled_bound", "group_test_miss", "group_covered", "pooled_covers_group", "exch_coverage", "pooled_exchangeable_coverage", "low_n"]])
    h1d = csv("coverage_by_typology.csv")
    section(out, "3b. H1 by typology, DIRECT scorer (delta 0.10, K = 1% and 5% of period)", "results/coverage_by_typology.csv",
            h1d[np.isclose(h1d.delta, 0.10) & h1d.K_frac.isin([0.01, 0.05])][["typology", "K_frac", "n_cal_pos", "n_test_pos", "group_cal_miss", "group_bound", "pooled_bound", "group_test_miss", "group_covered", "pooled_covers_group", "exch_coverage", "pooled_exchangeable_coverage", "low_n"]])
    w = csv("h1_bound_width_primary.csv")
    section(out, "3c. Bound width vs number of calibration positives (primary scorer, delta 0.10, K = 1%)", "results/h1_bound_width_primary.csv",
            w[np.isclose(w.delta, 0.10) & (w.K == w.K.unique()[1])][["typology", "n_cal_pos", "group_cal_miss", "group_bound", "bound_width"]])

    h3 = csv("h3_aggregation.csv")
    section(out, "4. H3 direct vs max-over-transaction (delta 0.10)", "results/h3_aggregation.csv", h3[np.isclose(h3.delta, 0.10)][["variant", "K_frac", "K", "certified_bound", "test_miss_realised", "covered", "recall_at_K_test", "control_coverage_vs_pooled"]])

    h2 = csv("h2_synthetic_delay.csv")
    section(out, "5. H2 synthetic dose-response (delta 0.10, last 10 periods)", "results/h2_synthetic_delay.csv (t = all)",
            h2[h2.t == "all"][["grid", "d", "L", "coverage", "se", "mean_bound", "mean_true_miss"]],
            note="grid = extended_post_hoc rows were added after the first freeze")

    sp = csv("elliptic_spike.csv")
    section(out, "6a. Elliptic spike (static bound from steps 25-34, delta 0.10)", "results/elliptic_spike.csv",
            sp[sp.role == "evaluation"][["step", "q", "n_labelled", "n_illicit", "realised_miss", "bound", "covered"]])
    h4 = csv("h4_elliptic_summary.csv")
    section(out, "6b. Elliptic arms: error frequency, mean bound, recovery lag", "results/h4_elliptic_summary.csv", h4,
            note="aci_offset* arms are post-hoc; err_freq_* use the binomial error indicator (target 0.10)")
    section(out, "6c. Bound vs delta (limited authority of delta)", "results/bound_vs_delta.csv", csv("bound_vs_delta.csv"), "{:.4f}")

    # ties / margin and Day 1 recall
    sc = pd.read_parquet(C.PROCESSED / "scores.parquet")
    te = sc[sc.split == "test"]
    ties = pd.DataFrame([{"test rows": len(te), "rows with probability exactly 1.0": int((te.score >= 1.0).sum()),
                          "share": (te.score >= 1.0).mean(), "distinct margins among those rows": int(te[te.score >= 1.0].margin.nunique()),
                          "rows sharing a margin within a period": int(te.duplicated(["period", "margin"], keep=False).sum())}])
    section(out, "7. Ties and margin ranking", "data/processed/scores.parquet (columns score, margin)", ties, "{:.4f}")
    new, old, v1 = (json.loads((R / f).read_text())["test"] for f in ("day1_model_metrics.json", "day1_model_metrics_v2_table_order_ties.json", "day1_model_metrics_v1_lookback_only.json"))
    rows = []
    for k in new["recall_at_k"]:
        rows.append({"K": k, "v1 lookback-only (prob, table-order ties)": v1["recall_at_k"][k]["pooled"],
                     "v2 (prob, table-order ties)": old["recall_at_k"][k]["pooled"], "v2 (margin, random ties)": new["recall_at_k"][k]["pooled"]})
    rows.append({"K": "ROC-AUC", "v1 lookback-only (prob, table-order ties)": v1["roc_auc"], "v2 (prob, table-order ties)": old["roc_auc"], "v2 (margin, random ties)": new["roc_auc"]})
    rows.append({"K": "PR-AUC", "v1 lookback-only (prob, table-order ties)": v1["pr_auc"], "v2 (prob, table-order ties)": old["pr_auc"], "v2 (margin, random ties)": new["pr_auc"]})
    section(out, "8. Day 1 test recall (pooled) and AUC", "results/day1_model_metrics*.json (test.recall_at_k.*.pooled, roc_auc, pr_auc)", pd.DataFrame(rows))

    # data-window numbers
    from src import data, panel
    trans = data.load_transactions()
    tx = panel.active_transactions(trans)
    pan = panel.build_panel()
    pos = pan[pan.label == 1]
    pats = data.load_patterns(trans)
    pos_tx = trans[trans.is_laundering == 1]
    in_pat = pos_tx.tx_id.isin(pats.tx_id.dropna().astype(int))
    win = pd.DataFrame([{
        "transactions (raw)": len(trans), "transactions kept (before 2022-09-11)": len(tx), "transactions dropped": len(trans) - len(tx),
        "laundering rows (raw)": int(trans.is_laundering.sum()), "laundering rows dropped by cutoff": int(trans.is_laundering.sum() - tx.is_laundering.sum()),
        "periods (12h)": int(pan.period.nunique()), "entity-periods": len(pan), "positive entity-periods": len(pos),
        "UNATTRIBUTED share of positive entity-periods": (pos.typology == "UNATTRIBUTED").mean(),
        "laundering transactions in no pattern attempt": int((~in_pat).sum()),
        "share of laundering transactions in no pattern attempt": float((~in_pat).mean())}]).T.reset_index()
    win.columns = ["quantity", "value"]
    section(out, "9. Data window and attribution", "data/processed/transactions.parquet, panel.parquet and HI-Small_Patterns.txt (via src/data.py, src/panel.py)", win, "{:.4f}")
    (C.ROOT / "report").mkdir(exist_ok=True)
    (C.ROOT / "report" / "numbers.md").write_text("\n".join(out))
    print(f"wrote report/numbers.md ({len(out)} lines)")


if __name__ == "__main__":
    main()
